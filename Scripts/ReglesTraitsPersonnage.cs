    public static IReadOnlyList<Definition> Evaluer(MembreGuilde membre, bool uniquementConnus = true)
    {
        if (membre == null) return System.Array.Empty<Definition>();
        return Definitions.Where(def => def.Conditions.All(c =>
            (!uniquementConnus || EstConnu(membre, c.Stat)) &&
            Valeur(membre, c.Stat) is int valeur &&
            (c.Minimum ? valeur >= c.Valeur : valeur <= c.Valeur))).ToList();
    }

    private static bool EstConnu(MembreGuilde m, string stat)
    {
        if (m.EstMaitreDeGuilde || m.EstJoueur) return true;
        if (stat == "Moral" || stat == "Bonheur" || stat == "Fatigue") return true;
        return m.ConnaitStatistique(CleStat(stat));
    }

    private static int? Valeur(MembreGuilde m, string stat)
    {
        return stat switch
        {
            "Motivation" => m.Motivation,
            "Fatigue" => m.Fatigue,
            "Moral" => m.Moral,
            "Bonheur" => m.Bonheur,
            _ => m.Statistiques.TryGetValue(CleStat(stat), out int nombre) ? nombre : null
        };
    }

    private static string CleStat(string nom)
    {
        // Les clés existantes des membres emploient Memoire / Volonte / Agilite.
        return nom switch
        {
            "Mémoire" => "Memoire",
            "Volonté" => "Volonte",
            "Agilité" => "Agilite",
            _ => nom
        };
    }

    public static string Afficher(IEnumerable<Definition> traits, bool negatifs)
    {
        string[] noms = traits.Where(t => t.EstNegatif == negatifs).Select(t => t.Nom).ToArray();
        return noms.Length == 0 ? "Aucun" : string.Join(", ", noms);
    }

